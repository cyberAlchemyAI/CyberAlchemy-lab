#!/usr/bin/env python3
"""Build and validate the repository's generated source inventory."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
INVENTORY = ROOT / ".arcanum" / "inventory"
MANIFEST = INVENTORY / "inventory.json"
INDEX = INVENTORY / "index.md"
EXCLUDED = {
    ".arcanum/inventory/inventory.json",
    ".arcanum/inventory/content-map.jsonl.gz",
    ".arcanum/inventory/content-search.sqlite3",
    ".arcanum/inventory/content-search.sqlite3-journal",
    ".arcanum/inventory/content-search.sqlite3-shm",
    ".arcanum/inventory/content-search.sqlite3-wal",
    ".arcanum/inventory/content-map-info.json",
}


def git_paths(*args: str) -> list[str]:
    result = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "-z", *args],
        check=True,
        stdout=subprocess.PIPE,
    )
    return [item.decode("utf-8", "surrogateescape") for item in result.stdout.split(b"\0") if item]


def extension(path: str) -> str:
    name = Path(path).name
    return Path(name).suffix.lower() or "[no extension]"


def digest(path: Path) -> tuple[str, int, str]:
    if path.is_symlink():
        value = os.readlink(path).encode("utf-8", "surrogateescape")
        return hashlib.sha256(value).hexdigest(), len(value), "symlink"
    hasher = hashlib.sha256()
    size = 0
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            hasher.update(block)
            size += len(block)
    return hasher.hexdigest(), size, "file"


def collect() -> dict:
    tracked = set(git_paths("--cached"))
    candidates = set(git_paths("--cached", "--others", "--exclude-standard"))
    paths = sorted(candidates - EXCLUDED)
    files = []
    directories: dict[str, Counter] = defaultdict(Counter)
    extensions: Counter = Counter()
    top_levels: Counter = Counter()

    for relative in paths:
        source = ROOT / relative
        if not source.is_file() and not source.is_symlink():
            continue
        sha256, size, kind = digest(source)
        ext = extension(relative)
        parts = Path(relative).parts
        top = parts[0] if len(parts) > 1 else "(root)"
        record = {
            "path": relative,
            "kind": kind,
            "tracking": "tracked" if relative in tracked else "untracked",
            "size_bytes": size,
            "sha256": sha256,
            "extension": ext,
        }
        files.append(record)
        extensions[ext] += 1
        top_levels[top] += 1
        for depth in range(1, len(parts)):
            directory = "/".join(parts[:depth])
            directories[directory]["files"] += 1
            directories[directory][ext] += 1

    return {
        "format": "cyberalchemy-lab-repository-inventory/v1",
        "repository": ".",
        "selection": {
            "includes": "tracked files and non-ignored untracked files present in the working tree",
            "excludes": [".git/**", "Git-ignored files", "empty directories", *sorted(EXCLUDED)],
            "symlinks": "hashed as their link-target text; targets are not followed",
        },
        "summary": {
            "file_count": len(files),
            "tracked_count": sum(f["tracking"] == "tracked" for f in files),
            "untracked_count": sum(f["tracking"] == "untracked" for f in files),
            "total_bytes": sum(f["size_bytes"] for f in files),
            "top_level_counts": dict(sorted(top_levels.items())),
            "extension_counts": dict(sorted(extensions.items(), key=lambda item: (-item[1], item[0]))),
        },
        "directories": [
            {"path": path, **dict(sorted(counts.items()))}
            for path, counts in sorted(directories.items())
        ],
        "files": files,
    }


def render_index(inventory: dict) -> str:
    summary = inventory["summary"]
    lines = [
        "# Repository Index",
        "",
        "Generated by [`tooling/inventory/build_inventory.py`](../../tooling/inventory/build_inventory.py).",
        "",
        f"- Files inventoried: **{summary['file_count']:,}** ({summary['tracked_count']:,} tracked, {summary['untracked_count']:,} untracked)",
        f"- Total file bytes: **{summary['total_bytes']:,}**",
        "- Complete path and SHA-256 manifest: [`inventory.json`](inventory.json)",
        "- Content outlines and full-text search: [`content-map.jsonl.gz`](content-map.jsonl.gz), [`content-search.sqlite3`](content-search.sqlite3), and [`content-map-info.json`](content-map-info.json).",
        "- Scope excludes Git internals, Git-ignored paths, empty directories, and generated self-referential inventory outputs.",
        "",
        "## Current-state views",
        "",
        "- [`queries/definitions-status.md`](queries/definitions-status.md) — governed Definition versions, current lookup, and candidate-package lineage.",
        "- [`queries/cyberalchemy-v2-migration-decisions.md`](queries/cyberalchemy-v2-migration-decisions.md) — migration decisions, approvals, admissions, and remaining execution boundary.",
        "- [`queries/governance-repository-map.md`](queries/governance-repository-map.md) — governance zones, exact status routes, and repository-wide integration map.",
        "",
        "## Repository map",
        "",
        "| Area | Files | Purpose |",
        "| --- | ---: | --- |",
    ]
    purposes = {
        ".arcanum": "Generated inventory and candidate ontology-vault analysis; navigation is not admission.",
        "authority": "Canonical governance artifacts, definitions, decisions, owners, profiles, and lineage.",
        "claude": "Local conversation context reference; no repository authority by itself.",
        "contexts": "Context maps and governance, lineage, migration, and lifecycle context.",
        "coordination": "Project, goal, and coordination context records.",
        "craft": "Craft capability, architecture, ontology, definitions, implementation, and research.",
        "docs": "Decision, proposal, plan, pack, bundle, and normalization documents.",
        "evidence": "Migration, validation, and conformance evidence records.",
        "implementation": "Runtime and implementation bindings.",
        "ontology-lifecycle": "Ontology lifecycle, activation, runtime candidates, conformance, fixtures, and benchmarks.",
        "product": "Product definitions and prototypes.",
        "tests": "Conformance tests and fixtures.",
        "tooling": "Generators, importers, schemas, validators, and inventory tooling.",
    }
    for area, purpose in purposes.items():
        count = summary["top_level_counts"].get(area, 0)
        lines.append(f"| [`{area}/`](../../{area}/) | {count:,} | {purpose} |")
    lines += [
        f"| Repository root | {summary['top_level_counts'].get('(root)', 0):,} | Foundation contract, repository metadata, and root-level artifacts. |",
        "",
        "## File type index",
        "",
        "Counts include tracked and non-ignored untracked files.",
        "",
        "| Type | Files |",
        "| --- | ---: |",
    ]
    lines.extend(f"| `{ext}` | {count:,} |" for ext, count in summary["extension_counts"].items())
    lines += [
        "",
        "## Browse by path",
        "",
        "The manifest is sorted by repository path and contains each file's tracking state, byte size, file kind, extension, and SHA-256. Directory rollups are also included for every path prefix.",
        "",
        "## Refresh and validate",
        "",
        "```sh",
        "python3 tooling/inventory/build_inventory.py",
        "python3 tooling/inventory/build_inventory.py --check",
        "```",
        "",
    ]
    return "\n".join(lines)


def write_outputs(inventory: dict) -> None:
    INVENTORY.mkdir(parents=True, exist_ok=True)
    # The index is itself inventoried, so write it before taking the final
    # snapshot. The JSON manifest is excluded to avoid recursive hashing.
    INDEX.write_text(render_index(inventory), encoding="utf-8")
    for _ in range(3):
        inventory = collect()
        rendered = render_index(inventory)
        if INDEX.read_text(encoding="utf-8") == rendered:
            break
        INDEX.write_text(rendered, encoding="utf-8")
    inventory = collect()
    MANIFEST.write_text(json.dumps(inventory, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def check_outputs(inventory: dict) -> list[str]:
    expected_json = json.dumps(inventory, indent=2, ensure_ascii=False) + "\n"
    expected_index = render_index(inventory)
    errors = []
    if not MANIFEST.is_file() or MANIFEST.read_text(encoding="utf-8") != expected_json:
        errors.append("inventory.json is missing or stale; run the builder")
    if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != expected_index:
        errors.append("index.md is missing or stale; run the builder")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate generated inventory without writing")
    args = parser.parse_args()
    inventory = collect()
    if args.check:
        errors = check_outputs(inventory)
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
        print(f"inventory valid: {inventory['summary']['file_count']} files")
        return 0
    write_outputs(inventory)
    print(f"inventoried {inventory['summary']['file_count']} files into {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
