#!/usr/bin/env python3
"""Generate all human projections for the thin Ontology Product candidate."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent


def header(source: str) -> list[str]:
    return [f"<!-- Generated from {source}. Do not edit. -->", ""]


def product_view(value: dict[str, Any]) -> str:
    lines = header("product.json") + ["# CyberAlchemy Ontology Product", "", f"- Product: `{value['product_id']}`", f"- Version: `{value['version']}`", f"- Status: `{value['status']}`", f"- Authority effect: `{value['authority_effect']}`", f"- Parent Product: `{value['parent_product_ref']}`", f"- Core output: `{value['core_output_ref']}`", f"- Product Ontology: `{value['product_ontology_ref']}`", "", "## Purpose", "", value["purpose"], "", "## Scope", "", "Included:", ""]
    lines.extend(f"- {item}" for item in value["scope"]["includes"])
    lines += ["", "Excluded:", ""]
    lines.extend(f"- {item}" for item in value["scope"]["excludes"])
    lines += ["", "## Test", "", "Run `PYTHONDONTWRITEBYTECODE=1 python3 product/products/ontology/v1/validate.py` from the Lab root.", "", "## Claim ceiling", "", value["claim_ceiling"], ""]
    return "\n".join(lines)


def ontology_view(value: dict[str, Any]) -> str:
    lines = header("product-ontology/ontology.json") + ["# Product Ontology", "", f"- Ontology: `{value['ontology_id']}`", f"- Represents: `{value['represented_product_ref']}`", f"- Role: `{value['role']}`", f"- Status: `{value['status']}`", f"- Authority effect: `{value['authority_effect']}`", "", "## Product graph", "", "| Node | Role | Type |", "| --- | --- | --- |"]
    lines.extend(f"| `{row['node_id']}` | `{row['role']}` | `{row['type_ref']}` |" for row in value["nodes"])
    lines += ["", "| Relation | Type | Source | Target |", "| --- | --- | --- | --- |"]
    lines.extend(f"| `{row['relation_id']}` | `{row['type_ref']}` | `{row['source_node_id']}` | `{row['target_node_id']}` |" for row in value["relations"])
    lines += ["", "## Non-collapse", ""]
    lines.extend(f"- `{item}`" for item in value["non_collapse_invariants"])
    lines += ["", "## Claim ceiling", "", value["claim_ceiling"], ""]
    return "\n".join(lines)


def closure_view(value: dict[str, Any]) -> str:
    lines = header("source-closure.json") + ["# Prototype source closure", "", f"- Closure: `{value['closure_id']}`", f"- Status: `{value['status']}`", f"- Authority effect: `{value['authority_effect']}`", "", value["dependency_policy"], "", "## Exact dependencies", "", "| Source | Root | Path | SHA-256 | Owner |", "| --- | --- | --- | --- | --- |"]
    lines.extend(f"| `{row['source_id']}` | `{row['root']}` | `{row['path']}` | `{row['sha256']}` | `{row['owner_route']}` |" for row in value["sources"])
    lines += ["", "## Diagnostic residue", ""]
    lines.extend(f"- `{row['residue_id']}` — {row['statement']} Status: `{row['status']}`." for row in value["diagnostic_residue"])
    lines += ["", "## Claim ceiling", "", value["claim_ceiling"], ""]
    return "\n".join(lines)


def source_view(value: dict[str, Any]) -> str:
    lines = header("fixtures/valid/source.json") + ["# Owner-selected source fixture", "", f"- Source: `{value['source_id']}`", f"- Package target: `{value['package_id']}`", f"- Domain: `{value['domain']}`", f"- Owner: `{value['owner_route']}`", f"- Authority effect: `{value['authority_effect']}`", "", "## Selected meaning", ""]
    lines.extend(f"- `{row['node_id']}` — {row['definition_or_claim']}" for row in value["nodes"])
    lines += ["", "## Relations", ""]
    lines.extend(f"- `{row['relation_id']}`: `{row['source_node_id']}` --`{row['type_ref']}`→ `{row['target_node_id']}`" for row in value["relations"])
    lines.append("")
    return "\n".join(lines)


def package_view(value: dict[str, Any]) -> str:
    lines = ["<!-- Generated by cal-ontology-product from ontology-package.json. Do not edit. -->", "", f"# Ontology package `{value['package_id']}`", "", f"- Version: `{value['version']}`", f"- Domain: `{value['domain']}`", f"- Status: `{value['status']}`", f"- Authority effect: `{value['authority_effect']}`", f"- Product: `{value['product_ref']}`", f"- Product output: `{value['product_output_ref']}`", f"- Source: `{value['source_binding']['source_id']}`", f"- Source digest: `{value['source_binding']['sha256']}`", "", "## Nodes", "", "| ID | Type | Label | Scope |", "| --- | --- | --- | --- |"]
    lines.extend(f"| `{row['node_id']}` | `{row['type_ref']}` | {row['label']} | {row['scope']} |" for row in value["nodes"])
    lines += ["", "## Relations", "", "| ID | Type | Source | Target |", "| --- | --- | --- | --- |"]
    lines.extend(f"| `{row['relation_id']}` | `{row['type_ref']}` | `{row['source_node_id']}` | `{row['target_node_id']}` |" for row in value["relations"])
    lines += ["", "## Residue", ""]
    if value["residue"]:
        lines.extend(f"- `{row['residue_id']}` — {row['statement']} Owner: `{row['owner_route']}`; treatment: `{row['treatment']}`." for row in value["residue"])
    else:
        lines.append("- None.")
    lines += ["", "## Query contract", "", f"- Allowed operations: `{'`, `'.join(value['query_contract']['allowed_operations'])}`", f"- Unknown identity: `{value['query_contract']['unknown_identity_behavior']}`", f"- Filesystem reach: `{value['query_contract']['filesystem_reach']}`", "", "## Claim ceiling", "", value["claim_ceiling"], ""]
    return "\n".join(lines)


def candidate_view(value: dict[str, Any]) -> str:
    lines = header("candidates/0001-thin-end-to-end/candidate.json") + ["# Thin end-to-end Ontology Product candidate", "", f"- Candidate: `{value['candidate_id']}`", f"- Version: `{value['version']}`", f"- Status: `{value['status']}`", f"- Authority effect: `{value['authority_effect']}`", "", "## Primary behavior", "", value["primary_behavior"], "", "## Acceptance criteria", ""]
    lines.extend(f"- {item}" for item in value["acceptance_criteria"])
    lines += ["", "## Test", "", f"Run `{value['test_command']}`.", "", "Try the CLI:", ""]
    lines.extend(f"- `{item}`" for item in value["try_commands"])
    lines += ["", "## Approval boundary", "", value["approval_boundary"], "", "## Claim ceiling", "", value["claim_ceiling"], ""]
    return "\n".join(lines)


def contracts_view(source_schema: dict[str, Any], package_schema: dict[str, Any]) -> str:
    return "\n".join(header("contracts/source.schema.json and contracts/ontology-package.schema.json") + ["# Ontology Product contracts", "", f"- Source contract: `{source_schema['$id']}`", f"- Package contract: `{package_schema['$id']}`", "- Both representations are closed (`additionalProperties: false`).", "- Rust applies graph, identity, authority, query, and projection checks after structural validation.", ""])


def projections() -> dict[Path, str]:
    load = lambda path: json.loads((ROOT / path).read_text())
    source_schema = load("contracts/source.schema.json")
    package_schema = load("contracts/ontology-package.schema.json")
    return {
        ROOT / "PRODUCT.md": product_view(load("product.json")),
        ROOT / "product-ontology/PRODUCT-ONTOLOGY.md": ontology_view(load("product-ontology/ontology.json")),
        ROOT / "SOURCE-CLOSURE.md": closure_view(load("source-closure.json")),
        ROOT / "contracts/CONTRACTS.md": contracts_view(source_schema, package_schema),
        ROOT / "fixtures/valid/SOURCE.md": source_view(load("fixtures/valid/source.json")),
        ROOT / "fixtures/valid/ONTOLOGY-PACKAGE.md": package_view(load("fixtures/valid/ontology-package.json")),
        ROOT / "candidates/0001-thin-end-to-end/CANDIDATE.md": candidate_view(load("candidates/0001-thin-end-to-end/candidate.json")),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    failures: list[str] = []
    for path, content in projections().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                failures.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(json.dumps({"result": "PASS" if not failures else "FAIL", "mode": "check" if args.check else "generate", "failures": failures}, indent=2))
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
