use cal_ontology_product::{
    OntologySource, build_package, canonical_json, get_node, human_projection, list_nodes,
    validate_package,
};
use cal_ontology_product_lifecycle_binding::{
    CONTEXT_MAP_REF, GOVERNANCE_CONTEXT_REF, LifecycleRuntimeBinding,
    ONTOLOGY_LIFECYCLE_CONTEXT_REF, ProductChangeBody, ProductEvolutionRuntime, ProductLifecycle,
    ReferenceEvolutionRuntime, changes_from_source, push_change,
};
use std::collections::BTreeSet;
use tempfile::tempdir;

const SOURCE: &[u8] = include_bytes!("../selected-source.json");

fn source() -> OntologySource {
    serde_json::from_slice(SOURCE).expect("selected source must parse")
}

fn evolved_changes() -> Vec<cal_ontology_product_lifecycle_binding::ProductChange> {
    let source = source();
    let mut changes = changes_from_source(&source).expect("source changes");
    let mut evolved = source
        .nodes
        .iter()
        .find(|node| node.node_id == "CA2-PRODUCT-ONTOLOGY")
        .expect("Product node")
        .clone();
    evolved.label = "CyberAlchemy Ontology Product — tested evolution".to_owned();
    push_change(
        &mut changes,
        ProductChangeBody::Node {
            node: evolved,
            lifecycle: ProductLifecycle::Active,
        },
    )
    .expect("evolution change");
    changes
}

#[test]
fn real_source_builds_one_deterministic_valid_package() {
    let first = build_package(SOURCE).expect("first package");
    let second = build_package(SOURCE).expect("second package");
    validate_package(&first).expect("valid package");
    assert_eq!(
        canonical_json(&first).unwrap(),
        canonical_json(&second).unwrap()
    );
    assert_eq!(first.nodes.len(), 23);
    assert_eq!(first.relations.len(), 24);
    assert_eq!(first.residue.len(), 5);
    assert_eq!(first.authority_effect, "none");
}

#[test]
fn bounded_retrieval_covers_every_node_and_unknown_identity_fails_closed() {
    let package = build_package(SOURCE).expect("package");
    let listed = list_nodes(&package);
    assert_eq!(listed.len(), 23);
    for node in listed {
        assert_eq!(get_node(&package, &node.node_id).unwrap(), node);
    }
    let error = get_node(&package, "CA2-NODE-DOES-NOT-EXIST").expect_err("unknown must fail");
    assert_eq!(error.code, "NODE_NOT_FOUND");
}

#[test]
fn source_references_and_graph_endpoints_are_closed() {
    let source = source();
    let node_ids = source
        .nodes
        .iter()
        .map(|node| node.node_id.as_str())
        .collect::<BTreeSet<_>>();
    assert!(source.nodes.iter().all(|node| !node.source_refs.is_empty()));
    assert!(source.relations.iter().all(|relation| {
        !relation.source_refs.is_empty()
            && node_ids.contains(relation.source_node_id.as_str())
            && node_ids.contains(relation.target_node_id.as_str())
    }));
}

#[test]
fn human_projection_is_deterministic_and_declares_generated_origin() {
    let package = build_package(SOURCE).expect("package");
    let first = human_projection(&package);
    let second = human_projection(&package);
    assert_eq!(first, second);
    assert!(first.starts_with("<!-- Generated by cal-ontology-product"));
    assert!(first.contains("Authority effect: `none`"));
}

#[test]
fn evolution_changes_observation_without_changing_authority_posture() {
    let changes = evolved_changes();
    let runtime = ReferenceEvolutionRuntime;
    let before = runtime.replay(&changes, changes.len() as u64 - 1).unwrap();
    let after = runtime.replay(&changes, changes.len() as u64).unwrap();
    assert_ne!(before.observation_digest, after.observation_digest);
    assert_eq!(after.authority_effect, "none");
    assert!(
        after
            .nodes
            .iter()
            .any(|node| node.label.ends_with("tested evolution"))
    );
}

#[test]
fn full_replay_and_checkpoint_recovery_are_byte_equivalent() {
    let changes = evolved_changes();
    let target = changes.len() as u64;
    let checkpoint = target / 2;
    let replay = LifecycleRuntimeBinding::new(tempdir().unwrap().path().join("replay"))
        .replay(&changes, target)
        .expect("full replay");
    let recovered = LifecycleRuntimeBinding::new(tempdir().unwrap().path().join("recovery"))
        .recover(&changes, checkpoint, target)
        .expect("checkpoint recovery");
    assert_eq!(
        serde_json::to_vec(&replay).unwrap(),
        serde_json::to_vec(&recovered).unwrap()
    );
}

#[test]
fn native_and_reference_runtimes_are_replaceable_behind_the_port() {
    let changes = evolved_changes();
    let target = changes.len() as u64;
    let native = LifecycleRuntimeBinding::new(tempdir().unwrap().path().join("native"))
        .replay(&changes, target)
        .expect("native runtime");
    let reference = ReferenceEvolutionRuntime
        .replay(&changes, target)
        .expect("reference runtime");
    assert_eq!(native, reference);
}

#[test]
fn context_observation_preserves_endpoint_and_map_boundaries() {
    let changes = evolved_changes();
    let target = changes.len() as u64;
    let observation = LifecycleRuntimeBinding::new(tempdir().unwrap().path().join("context"))
        .context_observation(&changes, target)
        .expect("context observation");
    assert_eq!(observation.governance_context_ref, GOVERNANCE_CONTEXT_REF);
    assert_eq!(
        observation.ontology_lifecycle_context_ref,
        ONTOLOGY_LIFECYCLE_CONTEXT_REF
    );
    assert_eq!(observation.context_map_ref, CONTEXT_MAP_REF);
    assert_eq!(observation.selected_node_ids.len(), 23);
    assert_eq!(observation.selected_relation_ids.len(), 24);
    assert_eq!(observation.authority_effect, "none");
    assert!(!observation.canonical_replay_source);
}

#[test]
fn authority_effect_mutation_is_rejected_before_package_construction() {
    let mut source = source();
    source.authority_effect = "admit".to_owned();
    let bytes = canonical_json(&source).unwrap();
    let error = build_package(&bytes).expect_err("authority mutation must fail");
    assert_eq!(error.code, "AUTHORITY_EFFECT_FORBIDDEN");
}
