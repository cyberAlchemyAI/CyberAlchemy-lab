"""Package-relative source consistency; not publisher authentication."""
import hashlib
import json
from pathlib import Path


class IntegrityError(ValueError):
    code = "runtime-source-drift"
    exit_code = 3


def require(condition, code, message=None, exit_code=3):
    if not condition:
        error = IntegrityError("Package consistency refused")
        error.code = code
        raise error


def verify():
    root = Path(__file__).resolve().parent
    manifest = json.loads((root / "runtime-manifest.json").read_bytes())
    require(manifest["schema_version"] == "define.portable-runtime-manifest/v1" and manifest["authority_effect"] == "none", "invalid-runtime-manifest", exit_code=3)
    rows = manifest["files"]
    canonical = (json.dumps(rows, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n").encode()
    require(hashlib.sha256(canonical).hexdigest() == manifest["inventory_sha256"], "runtime-inventory-mismatch", exit_code=3)
    paths = set()
    for row in rows:
        path = root / row["path"]
        require(path.is_relative_to(root) and ".." not in Path(row["path"]).parts and not Path(row["path"]).is_absolute()
                and path.resolve() == path and row["path"] not in paths, "runtime-path-mismatch", exit_code=3)
        paths.add(row["path"])
        raw = path.read_bytes()
        require(len(raw) == row["bytes"] and hashlib.sha256(raw).hexdigest() == row["sha256"], "runtime-source-drift", exit_code=3)
    for path in root.rglob("*"):
        if path.is_file() and path.suffix in (".py", ".so", ".pyd") and "__pycache__" not in path.parts:
            require(path.relative_to(root).as_posix() in paths, "unselected-runtime-source", exit_code=3)
    # Installed distributions may include generated bytecode: load selected source,
    # rather than trusting a cache which the source manifest does not select.
    from importlib.machinery import SourceFileLoader
    if not getattr(SourceFileLoader, "_define_core_guard", False):
        original = SourceFileLoader.get_code
        selected = {str(root / row["path"]): row["sha256"] for row in rows if row["path"].endswith(".py")}
        def source_code(loader, fullname):
            name = str(Path(loader.path).absolute())
            if name in selected:
                raw = Path(name).read_bytes()
                if hashlib.sha256(raw).hexdigest() != selected[name]:raise ImportError("Define selected source drift")
                return compile(raw, name, "exec", dont_inherit=True)
            return original(loader, fullname)
        SourceFileLoader.get_code = source_code
        SourceFileLoader._define_core_guard = True
    return {"checked_files": len(rows), "inventory_sha256": manifest["inventory_sha256"],
            "scope": "package-relative-drift-detection", "publisher_authentication": "not-established", "authority_effect": "none"}


def resource_bytes(name, maximum=16777216):
    """Portable installed-resource reads; no caller-controlled file access."""
    require(name in ("schema.json", "generator.py"), "unsupported-runtime-resource")
    root = Path(__file__).resolve().parent
    manifest = json.loads((root / "runtime-manifest.json").read_bytes())
    relative = "resources/" + name
    selected = [row for row in manifest["files"] if row["path"] == relative]
    require(len(selected) == 1 and selected[0]["bytes"] <= maximum, "invalid-runtime-resource")
    path = root / relative
    require(path.resolve() == path, "runtime-resource-path-mismatch")
    with path.open("rb") as handle:
        raw = handle.read(maximum + 1)
    row = selected[0]
    require(len(raw) == row["bytes"] and hashlib.sha256(raw).hexdigest() == row["sha256"], "runtime-resource-drift")
    return raw
