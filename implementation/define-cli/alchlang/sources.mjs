#!/usr/bin/env node
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import path from 'node:path';
const root=import.meta.dirname;
const selections=['sources.json','preparation-sources.json'].map(name=>({name,...JSON.parse(readFileSync(path.join(root,name)))}));
const files=[...new Set(selections.flatMap(s=>[s.primary,...s.additional]))].sort();
const actual=[];
function scan(directory,prefix=''){
 for(const entry of readdirSync(directory,{withFileTypes:true})){
  if(entry.name==='.local')continue;const name=prefix+entry.name;
  if(entry.isDirectory())scan(path.join(directory,entry.name),name+'/');else if(entry.isFile()&&name.endsWith('.alch'))actual.push(name);
 }
}
scan(root);
if(JSON.stringify(actual.sort())!==JSON.stringify(files))throw Error('Unselected or missing AlchLang source');
const counts={},modules={};let markdown='# Define: all authored AlchLang sources\n\nGenerated by `node sources.mjs`. Each deployment selects its own root; the two roots are never compiled together.\n';
for(const file of files){
 const text=readFileSync(path.join(root,file),'utf8'),module=/^module (\S+) version 1/m.exec(text)?.[1];if(!module)throw Error('Missing module: '+file);
 modules[file]=module;
 for(const match of text.matchAll(/^(value-object|enum|entity|operation|query|calculation|rule|policy|workflow|interface|event|mapping|state-machine|entry) (\S+?)(?: version \d+)?:/gm))counts[match[1]]=(counts[match[1]]??0)+1;
 markdown+='\n## '+file+'\n\n```alchlang\n'+text.trimEnd()+'\n```\n';
}
const index={schema_version:'cal.define.module-use-case-source-index/v1',alch_files:files.length,meta_types:counts,selections:selections.map(s=>({file:s.name,profile:s.profile??'profile.json',root:s.primary,entry:s.entry,alch_files:1+s.additional.length})),modules};
writeFileSync(path.join(root,'MODEL-INDEX.json'),JSON.stringify(index,null,2)+'\n');
writeFileSync(path.join(root,'ALL-ALCHLANG.md'),markdown);
console.log(JSON.stringify({alch_files:files.length,meta_types:counts,selections:index.selections},null,2));
