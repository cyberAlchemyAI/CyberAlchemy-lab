#!/usr/bin/env node
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import path from 'node:path';
const root=import.meta.dirname,selection=JSON.parse(readFileSync(path.join(root,'sources.json')));
const files=[selection.primary,...selection.additional].sort(),actual=[];
function scan(directory,prefix=''){
 for(const entry of readdirSync(directory,{withFileTypes:true})){
  if(entry.name==='.local'||entry.name==='__pycache__'||entry.name==='node_modules')continue;
  const name=prefix+entry.name;if(entry.isDirectory())scan(path.join(directory,entry.name),name+'/');else if(entry.isFile()&&name.endsWith('.alch'))actual.push(name);
 }
}
scan(root);if(JSON.stringify(actual.sort())!==JSON.stringify(files))throw Error('Missing or unselected authored AlchLang source');
let markdown='# Lab runtime: all authored AlchLang sources\n\nOne maintained model, selected by `sources.json`. Generated by `node sources.mjs`.\n';
const counts={},modules={},seen=new Set();
for(const file of files){
 const text=readFileSync(path.join(root,file),'utf8'),module=/^module (\S+) version 1/m.exec(text)?.[1];if(!module||seen.has(module))throw Error('Missing or duplicated module identity');seen.add(module);modules[file]=module;
 for(const match of text.matchAll(/^(value-object|enum|entity|operation|query|calculation|rule|policy|workflow|interface|event|mapping|state-machine|entry) (\S+?)(?: version \d+)?:/gm))counts[match[1]]=(counts[match[1]]??0)+1;
 markdown+='\n## '+file+'\n\n```alchlang\n'+text.trimEnd()+'\n```\n';
}
const index={schema_version:'cal.lab.authored-model-index/v1',alch_files:files.length,meta_types:counts,modules,entry:selection.entry};
writeFileSync(path.join(root,'ALL-ALCHLANG.md'),markdown);writeFileSync(path.join(root,'MODEL-INDEX.json'),JSON.stringify(index,null,2)+'\n');console.log(JSON.stringify(index,null,2));
