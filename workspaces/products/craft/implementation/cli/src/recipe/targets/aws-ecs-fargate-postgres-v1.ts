export function validateAwsRecipePolicy(artifacts: readonly PlannedDeploymentRecipeArtifactV1[]): true {
  const terraform = artifacts.filter(({ relative_path }) => relative_path.endsWith(".tf")).map(({ content }) => content).join("\n");
  for (const required of ["storage_encrypted           = true", "publicly_accessible         = false", "image_tag_mutability = \"IMMUTABLE\"", "readonlyRootFilesystem = true", "assign_public_ip = false", "manage_master_user_password = true", "sqs_managed_sse_enabled", "aws_sqs_queue_redrive_allow_policy", "sqs:SendMessage", "sqs:ReceiveMessage"]) if (!terraform.includes(required)) throw new Error(`MTCLI_RECIPE_POLICY_REQUIRED:${required}`);
  for (const artifact of artifacts) if (/-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|AKIA[0-9A-Z]{16}/.test(artifact.content)) throw new Error(`MTCLI_RECIPE_SECRET_LITERAL:${artifact.relative_path}`);
  if (terraform.includes("backend \"") || /(?:ip_)?protocol\s*=\s*"-1"[\s\S]{0,120}0\.0\.0\.0\/0/.test(terraform)) throw new Error("MTCLI_RECIPE_POLICY_FORBIDDEN");
  return true;
}
