function dockerfile(request: DeploymentRecipeRequestV1, role: "api" | "worker" | "consumer"): string {
  const command = role === "api" ? request.application.api.entrypoint : role === "worker" ? request.application.worker.entrypoint : request.application.consumer.entrypoint;
  const healthUrl = `http://127.0.0.1:${request.application.api.port}${request.application.api.health_path}`;
  const healthProbe = `fetch(${JSON.stringify(healthUrl)}).then(r=>{if(!r.ok)process.exit(1)}).catch(()=>process.exit(1))`;
  const health = role === "api" ? `HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 CMD ${JSON.stringify(["node", "-e", healthProbe])}\nEXPOSE ${request.application.api.port}\n` : "HEALTHCHECK NONE\n";
  return `# generated by DomainSpec ${DEPLOYMENT_RECIPE_TARGET}
# target-contract-sha256: ${AWS_RECIPE_TARGET_CONTRACT_SHA256}
ARG NODE_BASE_IMAGE=${request.application.base_image}
FROM \${NODE_BASE_IMAGE} AS build
WORKDIR /workspace
COPY application/package.json application/package-lock.json ./
RUN npm ci --ignore-scripts
COPY application/ ./
RUN npm run build

FROM \${NODE_BASE_IMAGE} AS runtime
ENV NODE_ENV=production
WORKDIR /app
COPY application/package.json application/package-lock.json ./
RUN npm ci --omit=dev --ignore-scripts && npm cache clean --force
COPY --from=build --chown=node:node /workspace/dist ./dist
USER node
STOPSIGNAL SIGTERM
${health}CMD ${JSON.stringify(command)}
`;
}

