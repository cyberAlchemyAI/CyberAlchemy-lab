import {domainSource} from '../../source-bindings.mjs';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const canonical=v=>JSON.stringify(v&&typeof v==='object'?Array.isArray(v)?v.map(x=>JSON.parse(canonical(x))):Object.fromEntries(Object.keys(v).sort().map(k=>[k,JSON.parse(canonical(v[k]))])):v);
const fail=message=>{throw new TypeError('DS_SOURCE_MATERIALIZATION:'+message);};
const root=path.resolve(import.meta.dirname,'..');
const selected=path.join(root,'contracts/reconciled-source-selection.json');
const output=path.join(root,'src/generation/reconciled-sources.generated.ts');
const keys=(v,want)=>{if(!v||typeof v!=='object'||Array.isArray(v)||canonical(Object.keys(v).sort())!==canonical([...want].sort()))fail('closed shape');};
export function materializeReconciledSources(selection,read) {
 keys(selection,['schema_version','authority_effect','sources']);
 if(selection.schema_version!=='domainspec.reconciled-source-selection/v1-candidate'||selection.authority_effect!=='none'||!Array.isArray(selection.sources)||!selection.sources.length)fail('selection');
 const ids=new Set(),paths=new Set(),rows=[];
 for(const s of selection.sources) {
  keys(s,['id','path','sha256']);
  if(typeof s.id!=='string'||!/^[a-z][a-z0-9_]*$/.test(s.id)||ids.has(s.id))fail('source ID');
  if(typeof s.path!=='string'||s.path.startsWith('/')||s.path.includes('\\')||path.posix.normalize(s.path)!==s.path||s.path.split('/').includes('..')||paths.has(s.path))fail('source path');
  if(typeof s.sha256!=='string'||!/^[a-f0-9]{64}$/.test(s.sha256))fail('digest');
  ids.add(s.id);paths.add(s.path);
  const content=read(s.path);
  if(typeof content!=='string'||hash(content)!==s.sha256)fail('source drift:'+s.id);
  rows.push({...s,content,size_bytes:Buffer.byteLength(content)});
 }
 rows.sort((a,b)=>a.id<b.id?-1:1);
 const body={schema_version:'domainspec.reconciled-source-capsule/v1-candidate',authority_effect:'none',selection_sha256:hash(canonical(selection)),sources:rows};
 return '// Generated by tools/materialize-reconciled-sources.mjs; do not hand edit.\n'+
  'export const RECONCILED_SOURCE_SNAPSHOT = '+JSON.stringify({...body,capsule_sha256:hash(canonical(body))},null,2)+' as const;\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href) {
 if(process.argv.length!==3||!['--check','--write'].includes(process.argv[2]))fail('use --check or --write');
 const text=materializeReconciledSources(JSON.parse(fs.readFileSync(selected,'utf8')),p=>{
  const file=domainSource(p);if(fs.realpathSync(file)!==file||!fs.lstatSync(file).isFile())fail('nonregular selected source');return fs.readFileSync(file,'utf8');
 });
 if(process.argv[2]==='--write')fs.writeFileSync(output,text);
 else if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==text)fail('generated capsule drift');
 console.log(JSON.stringify({status:'pass',mode:process.argv[2],sources:JSON.parse(fs.readFileSync(selected,'utf8')).sources.length,artifact:'src/generation/reconciled-sources.generated.ts'}));
}
