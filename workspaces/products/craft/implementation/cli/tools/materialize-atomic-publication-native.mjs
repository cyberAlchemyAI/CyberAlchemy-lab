#!/usr/bin/env node
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';

// Building is a maintainer operation. Checking and using the package require no compiler.
const root=path.resolve(import.meta.dirname,'..');
const source=path.join(root,'native/rename-noreplace.c');
const output=path.join(root,'src/generation/atomic-publication-native.generated.ts');
const digest=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const flags=['-std=c11','-O2','-shared','-fPIC','-fvisibility=hidden','-Wall','-Wextra','-Werror',
 '-nostdlib','-fno-stack-protector','-fno-builtin','-Wl,-z,relro,-z,now,-z,noexecstack','-DNAPI_VERSION=8'];
const sourceBytes=fs.readFileSync(source);
const buildDefinition={platform:'linux',arch:'x64',napi:8,flags,source_sha256:digest(sourceBytes)};
function render(payload){
 return '// Generated by tools/materialize-atomic-publication-native.mjs. Do not hand-edit.\n'+
  'export const ATOMIC_NATIVE = '+JSON.stringify(payload,null,2)+' as const;\n';
}
const mode=process.argv.slice(2);
if(mode.length!==1||!['--check','--write','--rebuild-check'].includes(mode[0]))throw Error('use --check, --write or --rebuild-check');
if(mode[0]==='--check'){
 const text=fs.readFileSync(output,'utf8');
 const payload=JSON.parse(text.slice(text.indexOf(' = ')+3,text.lastIndexOf(' as const;')));
 assert.equal(text,render(payload),'generated source shape drift');
 assert.deepEqual(payload.build,buildDefinition,'native source or build definition drift');
 const bytes=Buffer.from(payload.base64,'base64');
 assert.equal(bytes.toString('base64'),payload.base64,'noncanonical native payload');
 assert.equal(digest(bytes),payload.sha256,'native payload drift');
 assert.equal(bytes.length,payload.size_bytes,'native payload size drift');
 console.log(JSON.stringify({status:'pass',scope:'source-and-payload-currentness',bytes:bytes.length}));
}else{
 assert.equal(process.platform,'linux');assert.equal(process.arch,'x64');
 const compiler=process.env.DOMAINSPEC_NATIVE_CC;
 const readelf=process.env.DOMAINSPEC_NATIVE_READELF??'/usr/bin/readelf';
 assert.ok(compiler&&path.isAbsolute(compiler),'set DOMAINSPEC_NATIVE_CC to an absolute C compiler driver');
 const headers=path.resolve(path.dirname(process.execPath),'../include/node');
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'domainspec-native-build-'));
 try{
  const outputs=['first','second'].map(name=>{
   const dir=path.join(temp,name);fs.mkdirSync(dir);
   const input=path.join(dir,'primitive.c'),file=path.join(dir,'primitive.node');
   fs.writeFileSync(input,sourceBytes,{flag:'wx'});
   execFileSync(compiler,[...flags,'-I'+headers,input,'-o',file],{timeout:60000,stdio:'pipe'});
   return file;
  });
  const bytes=fs.readFileSync(outputs[0]);
  assert.deepEqual(bytes,fs.readFileSync(outputs[1]),'native build is path-dependent');
  const elf=args=>execFileSync(readelf,args.concat(outputs[0]),{encoding:'utf8',timeout:10000});
  assert.doesNotMatch(elf(['--dynamic']),/\(NEEDED\)/,'native artifact must not link runtime libraries');
  assert.doesNotMatch(elf(['--version-info']),/GLIBC_/,'native artifact must not require a glibc version');
  const imports=elf(['--wide','--dyn-syms']).split('\n').filter(l=>/\bUND\b/.test(l)).map(l=>l.trim().split(/\s+/)[7]).filter(Boolean);
  assert.ok(imports.length>0&&imports.every(n=>n.startsWith('napi_')),'unexpected native imports');
  const programHeaders=elf(['--wide','--program-headers']);
  assert.match(programHeaders,/GNU_RELRO/);assert.match(programHeaders,/GNU_STACK[^\n]+ RW /);
  const payload={build:buildDefinition,size_bytes:bytes.length,sha256:digest(bytes),base64:bytes.toString('base64')};
  const expected=render(payload);
  if(mode[0]==='--rebuild-check')assert.equal(fs.readFileSync(output,'utf8'),expected,'rebuilt native payload differs');
  else fs.writeFileSync(output,expected);
  console.log(JSON.stringify({status:mode[0]==='--write'?'written':'pass',scope:'reproducible-native-build',bytes:bytes.length,sha256:payload.sha256}));
 }finally{fs.rmSync(temp,{recursive:true,force:true});}
}
