import {domainSource} from '../../source-bindings.mjs';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {materializeReconciledSources} from './materialize-reconciled-sources.mjs';

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const canonical = v => JSON.stringify(v, (_, x) => x && typeof x === 'object' && !Array.isArray(x) ? Object.fromEntries(Object.entries(x).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) : x);
const fail = message => {throw new TypeError('CROSS_GENERATOR_MATERIALIZATION:' + message);};
const ids = ['verification', 'policy', 'execution', 'state_machine', 'factory', 'factory_execution', 'owned_values', 'owned_values_execution', 'value_producer', 'operation', 'operation_protocol', 'workflow', 'workflow_protocol', 'workflow_cases', 'workflow_observer', 'workflow_execution', 'workflow_public_evidence', 'public'].sort();
function inert(value, active = new Set()) {
  if (value === null || ['string', 'number', 'boolean'].includes(typeof value)) return;
  if (!value || typeof value !== 'object' || active.has(value)) fail('inert data');
  if (!Array.isArray(value) && ![Object.prototype, null].includes(Object.getPrototypeOf(value))) fail('inert data');
  active.add(value);
  for (const key of Reflect.ownKeys(value)) {
    if (typeof key !== 'string') fail('inert data');
    const d = Object.getOwnPropertyDescriptor(value, key);
    if (!d || !('value' in d)) fail('inert data');
    inert(d.value, active);
  }
  active.delete(value);
}
/** Reuse the qualified byte/path materializer without changing its original output. */
export function materializeCrossGeneratorSources(selection, read) {
  inert(selection);
  if (!selection || selection.schema_version !== 'domainspec.cross-generator-source-selection/v1-candidate') fail('selection version');
  if (!Array.isArray(selection.sources) || canonical(selection.sources.map(s => s.id).sort()) !== canonical(ids)) fail('complete selected contract inventory');
  const legacy = materializeReconciledSources({...selection, schema_version: 'domainspec.reconciled-source-selection/v1-candidate'}, read);
  const snapshot = JSON.parse(legacy.slice(legacy.indexOf(' = ') + 3, legacy.lastIndexOf(' as const;')));
  const body = {schema_version: 'domainspec.cross-generator-source-capsule/v1-candidate', authority_effect: 'none', selection_sha256: hash(canonical(selection)), sources: snapshot.sources};
  return '// Generated by tools/materialize-cross-generator-sources.mjs; do not hand edit.\n' +
    'export const CROSS_GENERATOR_SOURCE_SNAPSHOT = ' + JSON.stringify({...body, capsule_sha256: hash(canonical(body))}, null, 2) + ' as const;\n';
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.length !== 3 || !['--check', '--write'].includes(process.argv[2])) fail('use --check or --write');
  const root = path.resolve(import.meta.dirname, '..');
  const selection = JSON.parse(fs.readFileSync(path.join(root, 'contracts/cross-generator-source-selection.json'), 'utf8'));
  const output = path.join(root, 'src/verification/cross-generator-sources.generated.ts');
  const text = materializeCrossGeneratorSources(selection, p => {
    const file = domainSource(p);
    if (fs.realpathSync(file) !== file || !fs.lstatSync(file).isFile()) fail('nonregular selected source');
    return fs.readFileSync(file, 'utf8');
  });
  if (process.argv[2] === '--write') fs.writeFileSync(output, text);
  else if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== text) fail('generated capsule drift');
  console.log(JSON.stringify({status: 'pass', mode: process.argv[2], sources: selection.sources.length, artifact: 'src/verification/cross-generator-sources.generated.ts'}));
}
