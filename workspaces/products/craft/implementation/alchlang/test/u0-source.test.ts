test('U01 captured files detect content, same-byte replacement and symlink ownership drift',()=>{
 const root=mkdtempSync(path.join(os.tmpdir(),'alch-u01-'));
 try{
  const filename=path.join(root,'business.alch');writeFileSync(filename,source);
  const model=prepareBusinessSpecFileV2(root,'business.alch');assertResolvedBusinessSpecV2Current(model);
  writeFileSync(filename,source+'# changed\n');assert.throws(()=>assertResolvedBusinessSpecV2Current(model),/BUSINESS_SOURCE_DRIFT/);
  const next=prepareBusinessSpecFileV2(root,'business.alch');renameSync(filename,path.join(root,'original.alch'));writeFileSync(filename,source+'# changed\n');
  assert.throws(()=>assertResolvedBusinessSpecV2Current(next),/BUSINESS_SOURCE_DRIFT/);
  rmSync(filename);symlinkSync('original.alch',filename);
  assert.throws(()=>prepareBusinessSpecFileV2(root,'business.alch'),/BUSINESS_SOURCE_SYMLINK/);
  assert.throws(()=>assertResolvedBusinessSpecV2Current(next),/BUSINESS_SOURCE_SYMLINK/);
  assert.throws(()=>prepareBusinessSpecFileV2(root,'../business.alch'),/BUSINESS_SOURCE_PATH/);
 }finally{rmSync(root,{recursive:true,force:true});}
});
