import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { execFileSync } from "node:child_process";
import test from "node:test";
import { loadDomainSpecCompiler } from "../src/domainspec-cli.js";
import { prepareApplicationExecutable, compileApplicationExecutable } from "../src/application-executable.js";
import { executableFixture } from "./fixtures/application-executable-fixture.js";
import { realizationFixture } from "./fixtures/application-realization-fixture.js";
import { testTypeScript, testTsx } from "./toolchain.js";

function writeFiles(root: string, files: Record<string, string>) {
  for (const [relative, bytes] of Object.entries(files)) { const target = path.join(root, relative); mkdirSync(path.dirname(target), { recursive: true }); writeFileSync(target, bytes); }
}

test("execution binding preserves authored shape and cannot add hidden ports or guards", async () => {
  const compiler = await loadDomainSpecCompiler(); const f = executableFixture();
  const prepare = (execution: unknown) => prepareApplicationExecutable(f.source, f.bindings, f.sources, f.interpretation, execution, compiler);
  const candidate = prepare(f.execution);
  assert.deepEqual(candidate, prepare(f.execution)); assert.ok(Object.isFrozen(candidate.selection));
  for (const mutate of [
    (e: any) => { e.projection_sha256 = "0".repeat(64); },
    (e: any) => { e.selection.operations[0].inputs[0].type = { kind: "scalar", name: "Bool" }; },
    (e: any) => { e.selection.operations[0].result.type = { kind: "scalar", name: "String" }; },
    (e: any) => { e.selection.operations[0].reads = []; },
    (e: any) => { e.selection.operations[0].writes[0].target = "commerce:missing"; },
    (e: any) => { e.selection.operations[0].guards[0].selector = "commerce:identity-valid"; },
    (e: any) => { e.selection.operations[0].writes[0].slot = "hidden"; },
  ]) { const bad = structuredClone(f.execution); mutate(bad); assert.throws(() => prepare(bad), /APPLICATION_EXECUTION_/); }
});

for (const authored of [false, true]) test(`public DomainSpec API runs ${authored ? "source-derived realization" : "explicit legacy action"} with bounded transaction outcomes`, async t => {
  const compiler = await loadDomainSpecCompiler(); const f = authored ? realizationFixture() : executableFixture();
  const temp = mkdtempSync(path.join(tmpdir(), "alch-executable-")); t.after(() => rmSync(temp, { recursive: true, force: true }));
  const candidate = prepareApplicationExecutable(f.source, f.bindings, f.sources, f.interpretation, f.execution, compiler);
  if (authored) assert.deepEqual(candidate.selection.operations, executableFixture().execution.selection.operations, "authored connections derive the original exact action without supplied operation JSON");
  const sourceRoot = path.join(temp, "source"); writeFiles(sourceRoot, candidate.projectFiles);
  const graph = compiler.compileProject(sourceRoot).graph;
  const result = compileApplicationExecutable(candidate, graph, compiler);
  assert.deepEqual(result.view, compileApplicationExecutable(candidate, graph, compiler).view);
  assert.throws(() => compileApplicationExecutable(structuredClone(candidate), graph, compiler), /APPLICATION_EXECUTION_UNVALIDATED/);
  const worker = path.join(import.meta.dirname, "fixtures/application-executable-repeatability.ts");
  const mode = authored ? "realization" : "legacy";
  const first = execFileSync(process.execPath, [testTsx(), worker, sourceRoot, mode], { encoding: "utf8", env: { ...process.env, LANG: "C" } });
  const second = execFileSync(process.execPath, [testTsx(), worker, sourceRoot, mode], { encoding: "utf8", env: { ...process.env, LANG: "C.UTF-8" } });
  assert.equal(first, second, "fresh-process source, projection, join and generated bytes are repeatable");
  const generated = path.join(temp, "generated");
  writeFiles(generated, Object.fromEntries(result.view.artifacts.map(a => [a.relative_path, a.content])));
  execFileSync(process.execPath, [testTypeScript(), "--ignoreConfig", "--strict", "--skipLibCheck", "--target", "ES2022", "--module", "commonjs",
    "--rootDir", generated, "--outDir", path.join(temp, "js"), ...result.view.artifacts.map(a => path.join(generated, a.relative_path))], { encoding: "utf8" });
  const operation = result.view.artifacts.find(a => a.relative_path.endsWith("/operations/submit-order.ts"))!;
  assert.ok(operation, "native operation module exists");
  const run = createRequire(import.meta.url)(path.join(temp, "js", operation.relative_path.replace(/\.ts$/, ".js"))).operationSubmitOrder;
  for (const scenario of ["success", "guard-rejection", "missing", "commit-rejection", "commit-uncertain", "read-failure", "malformed"] as const) {
    const calls: string[] = []; const committed: unknown[] = [];
    const store = { begin: async () => { calls.push("begin"); return {
      read: async () => { calls.push("read"); if (scenario === "read-failure") throw Error("read failed"); return scenario === "missing" ? null : { id: "1", accepted: scenario !== "guard-rejection" }; },
      commit: async (batch: unknown) => { calls.push("commit"); if (scenario === "commit-uncertain") throw Error("unknown settlement");
        if (scenario === "commit-rejection") return { status: "rejected" }; committed.push(batch); return { status: "committed" }; },
      rollback: async () => { calls.push("rollback"); },
    }; } };
    const replacementAccepted = scenario !== "success";
    const outcome = await run({ request: { id: scenario === "malformed" ? "-1" : "1", accepted: replacementAccepted } }, { store, clocks: {} });
    if (scenario === "success") {
      assert.equal(outcome.status, "committed"); assert.deepEqual(outcome.value, { id: 1n, accepted: false });
      assert.equal(committed.length, 1); assert.deepEqual(calls, ["begin", "read", "commit"]);
      assert.deepEqual(committed[0], { writes: [{ slot: "commerce:order", target: "commerce:order", mode: "replace", value: { id: 1n, accepted: false } }], events: [] });
    } else {
      assert.notEqual(outcome.status, "committed", scenario); assert.equal(committed.length, 0);
      const expected = {
        "guard-rejection": ["rejected", "guard", "RULE_REJECTED:commerce:eligible-order"],
        missing: ["failed", "read", "READ_NOT_FOUND"],
        "commit-rejection": ["rejected", "commit", "COMMIT_REJECTED"],
        "commit-uncertain": ["indeterminate", "commit", "COMMIT_UNCERTAIN"],
        "read-failure": ["failed", "read", "OPERATION_FAILED"],
        malformed: ["failed", "input", "OPERATION_INPUT"],
      }[scenario];
      assert.deepEqual([outcome.status, outcome.stage, outcome.code], expected);
      assert.equal(outcome.continuation, "return-submission-error");
      if (scenario === "guard-rejection" || scenario === "missing" || scenario === "read-failure") assert.deepEqual(calls, ["begin", "read", "rollback"]);
      if (scenario === "malformed") assert.deepEqual(calls, []);
      if (scenario.startsWith("commit-")) assert.deepEqual(calls, ["begin", "read", "commit"]);
    }
  }
  // A compilable guard-bypass mutant must fail the independently stated rejection oracle.
  const provider = result.view.artifacts.find(a => a.relative_path.endsWith("/operations/submit-order.provider.ts"))!;
  const bypass = provider.content.replace("if(!guard0(", "if(false && !guard0(");
  assert.notEqual(bypass, provider.content);
  writeFiles(generated, { [provider.relative_path]: bypass });
  const mutantRoot = path.join(temp, "mutant-js");
  execFileSync(process.execPath, [testTypeScript(), "--ignoreConfig", "--strict", "--skipLibCheck", "--target", "ES2022", "--module", "commonjs",
    "--rootDir", generated, "--outDir", mutantRoot, ...result.view.artifacts.map(a => path.join(generated, a.relative_path))], { encoding: "utf8" });
  const mutantRun = createRequire(import.meta.url)(path.join(mutantRoot, operation.relative_path.replace(/\.ts$/, ".js"))).operationSubmitOrder;
  const mutantResult = await mutantRun({ request: { id: "1", accepted: true } }, { store: { begin: async () => ({
    read: async () => ({ id: "1", accepted: false }), commit: async () => ({ status: "committed" }), rollback: async () => {},
  }) } });
  assert.equal(mutantResult.status, "committed", "guard bypass wrongly commits despite successful native compilation");
  assert.throws(() => assert.equal(mutantResult.status, "rejected"), "independent rejection oracle detects the compilable semantic mutant");
  // Changing current source bytes cannot be concealed by recompiling a valid graph.
  const changed = { ...candidate.projectFiles, "project.json": candidate.projectFiles["project.json"]! + " " };
  writeFiles(sourceRoot, changed);
  const stale = compiler.compileProject(sourceRoot).graph;
  assert.throws(() => compileApplicationExecutable(candidate, stale, compiler), /APPLICATION_EXECUTION_GRAPH/);
});
