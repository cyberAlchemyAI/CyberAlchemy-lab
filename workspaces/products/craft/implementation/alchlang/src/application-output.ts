import { closeSync, constants, fstatSync, lstatSync, mkdirSync, openSync, readFileSync, readdirSync, realpathSync, rmdirSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { CompilationRejected } from "./model.js";
import { digest } from "./domainspec-profile.js";

export const APPLICATION_MANIFEST = ".alch/manifest.json";
const fail = (message: string): never => { throw new CompilationRejected([{ code: "APPLICATION_OUTPUT", path: "$output", message }]); };
const order = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0;
function stat(file: string) {
  try { return lstatSync(file); } catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined; throw error; }
}

/** Portable paths are validated as a complete set before creating a destination. */
export function validateApplicationOutput(files: Readonly<Record<string, string>>): void {
  const paths = new Map<string, string>(), originals = new Set(Object.keys(files));
  for (const relative of originals) {
    const parts = relative.split("/");
    if (!relative || parts.some(p => !p || p === "." || p === ".." || /[<>:"\\|?*\x00-\x1f]/.test(p) || /[. ]$/.test(p)
      || /^(?:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)/i.test(p))) fail("unsafe output path");
    for (let i = 1; i <= parts.length; i++) {
      const original = parts.slice(0, i).join("/"), key = original.normalize("NFKC").toLowerCase();
      if (paths.has(key) && paths.get(key) !== original) fail("portable output path collision");
      paths.set(key, original);
      if (i < parts.length && originals.has(original)) fail("output file/directory collision");
    }
    if (typeof files[relative] !== "string") fail("text artifact required");
  }
}

/** Exact comparison to independently regenerated bytes, not trust in an on-disk manifest. */
export function verifyApplicationOutput(directory: string, files: Readonly<Record<string, string>>): void {
  validateApplicationOutput(files);
  const root = path.resolve(directory), rootStat = stat(root);
  if (!rootStat || !rootStat.isDirectory() || rootStat.isSymbolicLink() || realpathSync(root) !== root) return fail("real output directory required");
  const expectedDirs = new Set<string>();
  for (const relative of Object.keys(files)) {
    const parts = relative.split("/");
    for (let i = 1; i < parts.length; i++) expectedDirs.add(parts.slice(0, i).join("/"));
  }
  const seen = new Set<string>();
  const walk = (dir: string, prefix: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const relative = prefix + entry.name, target = path.join(dir, entry.name), before = lstatSync(target);
      if (before.isSymbolicLink() || realpathSync(target) !== target) fail("symlink output");
      if (before.isDirectory()) {
        if (!expectedDirs.has(relative)) fail("unexpected output directory");
        walk(target, relative + "/");
      } else {
        if (!before.isFile() || !Object.hasOwn(files, relative)) fail("unexpected output file");
        const expected = files[relative]!;
        if (before.size !== Buffer.byteLength(expected)) fail("output byte size differs");
        const fd = openSync(target, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
        try {
          const opened = fstatSync(fd);
          if (!opened.isFile() || opened.ino !== before.ino || opened.dev !== before.dev || opened.size !== before.size) fail("output changed while opening");
          const bytes = readFileSync(fd), after = fstatSync(fd), present = lstatSync(target);
          if (digest(bytes) !== digest(expected) || after.size !== opened.size || after.mtimeMs !== opened.mtimeMs || after.ctimeMs !== opened.ctimeMs
            || present.ino !== after.ino || present.dev !== after.dev || present.isSymbolicLink() || realpathSync(target) !== target) fail("output bytes differ or changed while reading");
        } finally { closeSync(fd); }
        seen.add(relative);
      }
    }
  };
  walk(root, "");
  const after = lstatSync(root);
  if (after.ino !== rootStat.ino || after.dev !== rootStat.dev || realpathSync(root) !== root || seen.size !== Object.keys(files).length) fail("missing or replaced output");
}

export function assertApplicationOutputTarget(directory: string) {
  const root = path.resolve(directory), parent = path.dirname(root), parentStat = stat(parent);
  if (!parentStat || !parentStat.isDirectory() || parentStat.isSymbolicLink() || realpathSync(parent) !== parent) return fail("existing real output parent required");
  if (stat(root)) fail("output already exists");
  return { root, parent, parentStat };
}

/** No overwrite. The completion marker is written last; cleanup touches owned inodes only. */
export function writeApplicationOutput(directory: string, files: Readonly<Record<string, string>>, assertCurrent: () => void): void {
  validateApplicationOutput(files);
  if (!Object.hasOwn(files, APPLICATION_MANIFEST)) fail("completion manifest required");
  const { root, parent, parentStat } = assertApplicationOutputTarget(directory);
  assertCurrent();
  const owned: Array<{ file: string; ino: number; dev: number; directory: boolean; sha256?: string }> = [];
  const remember = (file: string, directory: boolean) => { const s = lstatSync(file); owned.push({ file, ino: s.ino, dev: s.dev, directory }); };
  const intact = (file: string): boolean => {
    const p = stat(parent);
    if (!p || p.ino !== parentStat.ino || p.dev !== parentStat.dev || p.isSymbolicLink() || realpathSync(parent) !== parent) return false;
    return owned.filter(item => item.directory && (file === item.file || file.startsWith(item.file + path.sep))).every(item => {
      const s = stat(item.file); return !!s && s.isDirectory() && !s.isSymbolicLink() && s.ino === item.ino && s.dev === item.dev;
    });
  };
  try {
    mkdirSync(root); remember(root, true);
    const names = Object.keys(files).sort(order).filter(name => name !== APPLICATION_MANIFEST);
    names.push(APPLICATION_MANIFEST);
    for (const relative of names) {
      if (!intact(root)) fail("output root replaced");
      if (relative === APPLICATION_MANIFEST) {
        assertCurrent();
        verifyApplicationOutput(root, Object.fromEntries(names.filter(name => name !== APPLICATION_MANIFEST).map(name => [name, files[name]!])));
      }
      let dir = root;
      for (const part of relative.split("/").slice(0, -1)) {
        dir = path.join(dir, part);
        if (!intact(dir)) fail("output parent replaced");
        if (!stat(dir)) { mkdirSync(dir); remember(dir, true); }
        else if (!owned.some(item => item.file === dir && item.directory)) fail("foreign output directory");
      }
      const target = path.join(root, relative);
      if (!intact(target)) fail("output path replaced");
      const fd = openSync(target, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o666);
      try {
        const s = fstatSync(fd), item = { file: target, ino: s.ino, dev: s.dev, directory: false, sha256: digest("") }; owned.push(item);
        writeFileSync(fd, files[relative]!);
        item.sha256 = digest(files[relative]!);
      } finally { closeSync(fd); }
    }
    verifyApplicationOutput(root, files);
    assertCurrent();
  } catch (error) {
    for (const item of [...owned].reverse()) {
      try {
        const s = stat(item.file);
        if (s && intact(item.file) && s.ino === item.ino && s.dev === item.dev && !s.isSymbolicLink()) {
          if (item.directory) rmdirSync(item.file);
          else if (item.sha256 === digest(readFileSync(item.file))) unlinkSync(item.file);
        }
      } catch { /* Preserve replacements and foreign additions; never recursively delete output. */ }
    }
    throw error;
  }
}
