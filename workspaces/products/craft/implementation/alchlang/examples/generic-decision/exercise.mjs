import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const directory=path.resolve(process.argv[2]??'generated');
const {evaluate}=await import(pathToFileURL(path.join(directory,'operation.mjs')).href);
const input=JSON.parse(readFileSync(new URL('./input.json',import.meta.url),'utf8'));
const wire=value=>new TextEncoder().encode(JSON.stringify(value));
async function run(value){const result=await evaluate(wire(value));assert.equal(result.ok,true,JSON.stringify(result.error));return JSON.parse(new TextDecoder().decode(result.wire));}
const normal=await run(input);assert.equal(normal.tag,'Returned');
const decision=normal.fields.value;
assert.equal(decision.approved,true);assert.equal(decision.decisionId,'23');
assert.deepEqual(decision.scores,['4','8','8']);assert.equal(decision.total,'20');
assert.deepEqual(decision.items.map(item=>item.itemId),['2','4','3']);
assert.deepEqual(decision.result,{tag:'Scored',fields:{total:'20'}});
assert.deepEqual(decision.proposal,{tag:'transition',state:'Approved',intents:[],machine:'ReviewDesk.Approval',branch:'transition:0',reason:'matched'});
assert.deepEqual(decision.note,{manual:null});
console.log(JSON.stringify({case:'normal',decision},null,2));
const priority=structuredClone(input);priority.request.flagged=true;
assert.equal((await run(priority)).fields.value.total,'30');
console.log('Priority Policy selects total 30.');
const natural=structuredClone(input);for(const item of natural.request.items)if(item.eligible)item.amount='4';
const sorted=(await run(natural)).fields.value;
assert.deepEqual(sorted.items.map(item=>item.label),['item2','item2','item10']);
assert.deepEqual(sorted.items.map(item=>item.itemId),['2','4','3']);assert.equal(sorted.total,'24');
console.log('Equal amounts use natural label order; equal keys preserve occurrence order.');
const stay=structuredClone(input);stay.request.state='Review';stay.request.signal='Cancel';
const retained=(await run(stay)).fields.value.proposal;
assert.equal(retained.tag,'stayed');assert.equal(retained.state,'Review');
console.log('Review/Cancel keeps the supplied state.');
const terminal=structuredClone(input);terminal.request.state='Approved';terminal.request.signal='Hold';
assert.equal((await run(terminal)).fields.value.proposal.state,'Approved');
const denied=structuredClone(input);denied.request.verified=false;
