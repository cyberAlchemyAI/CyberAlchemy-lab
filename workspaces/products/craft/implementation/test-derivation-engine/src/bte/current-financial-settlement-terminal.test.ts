import { describe, expect, it } from "vitest";

import { createCurrentFinancialSettlementDevelopmentProject } from "./current-financial-settlement.js";
import { runDevelopmentBte } from "./development-pipeline.js";
import { verifyCurrentFinancialSettlementTerminal } from "./current-financial-settlement-terminal.js";
import { sha256 } from "./validation/validate-semantics.js";

describe("current financial-settlement BTE terminal v1", () => {
  it("binds current source and generated bytes to 24 executed cases and a candidate receipt", () => {
    const first = verifyCurrentFinancialSettlementTerminal();
    const second = verifyCurrentFinancialSettlementTerminal();
    expect(first.reportBytes).toBe(second.reportBytes);
    expect(first.receiptBytes).toBe(second.receiptBytes);
    expect(first.receipt.report_sha256).toBe(sha256(first.reportBytes));
    expect(first.report).toMatchObject({
      schema_version: "bte-current-financial-settlement-terminal-report/v1",
      source_input_count: 7,
      source_record_count: 9,
      executed: 24,
      passed: 24,
      result: "pass",
      admission: "candidate-structural-only",
    });
    expect(first.report.negative_controls).toHaveLength(3);
    expect(first.report.catalogues.map(({ executed }) => executed)).toEqual([4, 4, 4, 5, 3, 4]);
    expect(Object.keys(first.report.generated)).toEqual([
      "graph.json",
      "source-manifest.json",
      "build-receipt.json",
      "markdown-view.json",
      "SPEC.md",
    ]);
  });

  it("rejects a substituted execution even if its summary is left intact", () => {
    const run = runDevelopmentBte(createCurrentFinancialSettlementDevelopmentProject());
    run.core.catalogueRuns[0]!.executions[0]!.status = "fail";
    expect(() => verifyCurrentFinancialSettlementTerminal(run)).toThrow(
      "BTE_CURRENT_TERMINAL_INVALID:core-replay",
    );
  });
});
