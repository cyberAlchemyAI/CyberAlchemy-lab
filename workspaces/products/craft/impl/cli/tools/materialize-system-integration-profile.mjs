#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, "../../system-integration");
const outputPath = path.resolve(here, "../src/system-integration/frozen-profile.generated.ts");
const profilePath = "profiles/provider-neutral-v1/profile.json";
const languagePaths = Object.freeze({
  typescript: "profiles/provider-neutral-v1/typescript.json",
  python: "profiles/provider-neutral-v1/python.json",
  rust: "profiles/provider-neutral-v1/rust.json",
});
const canonicalJson = (value) => Array.isArray(value)
  ? `[${value.map(canonicalJson).join(",")}]`
  : value !== null && typeof value === "object"
    ? `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(",")}}`
    : JSON.stringify(value);
const sha256 = (value) => crypto.createHash("sha256").update(value).digest("hex");
const read = (relativePath) => JSON.parse(fs.readFileSync(path.join(packageRoot, relativePath), "utf8"));

export function materializeSystemIntegrationProfileSource() {
  const profile = read(profilePath);
  if (profile.profile_id !== "domainspec.system-integration-profile/provider-neutral-v1" || profile.status !== "canonical-target" || profile.contract_kinds?.length !== 5) throw new Error("system-integration profile drift");
  const languages = Object.fromEntries(Object.entries(languagePaths).map(([language, relativePath]) => {
    const value = read(relativePath);
    if (value.language !== language || value.system_profile_ref !== profile.profile_id || value.semantic_obligations?.length !== 5) throw new Error(`system-integration language profile drift:${language}`);
    return [language, { value, digest: sha256(canonicalJson(value)) }];
  }));
  return [
    "// Generated by cli/tools/materialize-system-integration-profile.mjs. Do not hand-edit.",
    "import type { FrozenSystemIntegrationProfileV1 } from \"./types.js\";",
    "",
    `export const FROZEN_SYSTEM_INTEGRATION_PROFILE: FrozenSystemIntegrationProfileV1 = ${JSON.stringify({ profile, profile_digest: sha256(canonicalJson(profile)), language_profiles: languages }, null, 2)};`,
    "",
  ].join("\n");
}

const expected = materializeSystemIntegrationProfileSource();
if (process.argv.includes("--check")) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== expected) {
    process.stderr.write("frozen system-integration profile projection is stale\n");
    process.exitCode = 1;
  } else {
    process.stdout.write(`${JSON.stringify({ status: "pass", profile: path.relative(process.cwd(), outputPath), definitions: 5, languages: 3 })}\n`);
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected, "utf8");
  process.stdout.write(`${JSON.stringify({ status: "written", profile: path.relative(process.cwd(), outputPath), definitions: 5, languages: 3 })}\n`);
}
