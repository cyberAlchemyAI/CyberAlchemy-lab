#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const baselinePath = path.resolve(here, "../../../development/meta-type-instantiation-cli/CANONICAL-IMPLEMENTED-BASELINE.v10.json");
const outputPath = path.resolve(here, "../src/meta-types/frozen-catalog.generated.ts");
const receiptSchemaPath = path.resolve(here, "../contracts/instantiation-receipt.schema.json");
const expectedBaselineId = "domainspec-meta-types-current-implemented@10";
const expectedBaselineDigest = "bfbc335d151ab8b29150dc95f246c2bc0954cff179ece5ce51222b2d1455abda";
const sha256 = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");

export function materializeCatalogSource() {
  const baselineBytes = fs.readFileSync(baselinePath);
  const baseline = JSON.parse(baselineBytes.toString("utf8"));
  if (baseline.baseline_id !== expectedBaselineId || baseline.baseline_digest !== expectedBaselineDigest) {
    throw new Error("frozen baseline identity or digest drift");
  }
  if (baseline.backend_meta_types?.length !== 13 || baseline.realization_rows?.length !== 39) {
    throw new Error("frozen catalog denominator drift");
  }
  const keys = new Set();
  for (const row of baseline.realization_rows) {
    const key = `${row.meta_type_id}/${row.language}`;
    if (keys.has(key)) throw new Error(`duplicate frozen realization row:${key}`);
    keys.add(key);
    if (!baseline.backend_meta_types.some(({ id }) => id === row.meta_type_id)) throw new Error(`unknown frozen meta-type:${key}`);
    if (!["typescript", "python", "rust"].includes(row.language)) throw new Error(`unknown frozen language:${key}`);
    for (const role of ["source", "provider", "binding"]) {
      if (!row[role] || !/^[a-f0-9]{64}$/.test(row[role].sha256)) throw new Error(`invalid ${role} digest:${key}`);
    }
  }
  if (keys.size !== 39) throw new Error("frozen catalog coverage drift");
  const projection = {
    schema_version: "domainspec.meta-type-catalog/v2",
    baseline_id: baseline.baseline_id,
    baseline_digest: baseline.baseline_digest,
    manifest_sha256: sha256(baselineBytes),
    backend_meta_types: baseline.backend_meta_types,
    realization_rows: baseline.realization_rows,
  };
  const receiptBaseline = JSON.parse(fs.readFileSync(receiptSchemaPath, "utf8"))?.properties?.baseline?.properties;
  if (
    receiptBaseline?.id?.const !== projection.baseline_id
    || receiptBaseline?.digest?.const !== projection.baseline_digest
    || receiptBaseline?.manifest_sha256?.const !== projection.manifest_sha256
  ) {
    throw new Error("receipt schema baseline projection drift");
  }
  return [
    "// Generated by cli/tools/materialize-frozen-catalog.mjs. Do not hand-edit.",
    "import type { FrozenCatalogV2 } from \"./types.js\";",
    "",
    `export const FROZEN_CATALOG_V2: FrozenCatalogV2 = ${JSON.stringify(projection, null, 2)};`,
    "",
  ].join("\n");
}

const expected = materializeCatalogSource();
if (process.argv.includes("--check")) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== expected) {
    process.stderr.write("frozen catalog projection is stale\n");
    process.exitCode = 1;
  } else {
    process.stdout.write(`${JSON.stringify({ status: "pass", catalog: path.relative(process.cwd(), outputPath), rows: 39 })}\n`);
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected, "utf8");
  process.stdout.write(`${JSON.stringify({ status: "written", catalog: path.relative(process.cwd(), outputPath), rows: 39 })}\n`);
}
