#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(here, "../../../definitions/relationships/relationships.yml");
const outputPath = path.resolve(here, "../src/relationships/frozen-authority.generated.ts");
const expectedSourceSha256 = "82c55ea1ad031d3135c5b8a85162e44b4e85f296b54057fda0dc38131ab376a1";
const sha256 = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");

function array(value) {
  return Array.isArray(value) ? value : typeof value === "string" ? [value] : [];
}

export function materializeRelationshipAuthoritySource() {
  const sourceBytes = fs.readFileSync(sourcePath);
  const sourceDigest = sha256(sourceBytes);
  if (sourceDigest !== expectedSourceSha256) throw new Error("relationship authority source digest drift");
  const authority = JSON.parse(sourceBytes.toString("utf8"));
  if (authority.status !== "active" || authority.signature_count !== 31 || authority.signatures?.length !== 31) throw new Error("relationship authority denominator drift");
  const signatures = authority.signatures.map((signature) => ({
    id: signature.id,
    source_types: array(signature.source_types ?? signature.source_type),
    target_types: array(signature.target_types ?? signature.target_type),
    multiplicity: signature.multiplicity,
    feature_scope: signature.feature_scope,
    inverse: signature.inverse,
    validation_obligations: signature.validation?.obligations ?? [],
    ...(signature.generated_source_projection ? { generated_source_projection: signature.generated_source_projection } : {}),
  }));
  const projection = {
    schema_version: "domainspec.relationship-authority/v1",
    source_path: "projects/domainspec-v2/definitions/relationships/relationships.yml",
    source_sha256: sourceDigest,
    signature_count: 31,
    signatures,
    generated_views: (authority.generated_views ?? []).map(({ id, from_signature, source_type, target_type }) => ({ id, from_signature, source_type, target_type })),
    deprecated: (authority.deprecated ?? []).map(({ id, replacement, reason }) => ({ id, replacement, reason })),
  };
  return [
    "// Generated by cli/tools/materialize-relationship-authority.mjs. Do not hand-edit.",
    "import type { FrozenRelationshipAuthorityV1 } from \"./types.js\";",
    "",
    `export const FROZEN_RELATIONSHIP_AUTHORITY_V1: FrozenRelationshipAuthorityV1 = ${JSON.stringify(projection, null, 2)};`,
    "",
  ].join("\n");
}

const expected = materializeRelationshipAuthoritySource();
if (process.argv.includes("--check")) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== expected) {
    process.stderr.write("frozen relationship authority projection is stale\n");
    process.exitCode = 1;
  } else {
    process.stdout.write(`${JSON.stringify({ status: "pass", authority: path.relative(process.cwd(), outputPath), signatures: 31 })}\n`);
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected, "utf8");
  process.stdout.write(`${JSON.stringify({ status: "written", authority: path.relative(process.cwd(), outputPath), signatures: 31 })}\n`);
}
