import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

const here = dirname(fileURLToPath(import.meta.url));
const fixtureRoot = resolve(here, "../fixtures/can-settle-payout");

describe("Rule contract ownership boundaries", () => {
  it("keeps expected obligations and mutants separate from the handwritten body", async () => {
    const [obligations, mutants, source] = await Promise.all([
      readFile(resolve(fixtureRoot, "obligations.json"), "utf8"),
      readFile(resolve(fixtureRoot, "mutants.json"), "utf8"),
      readFile(resolve(here,
        "../../../realizations/rule/typescript/bound-arrow-function-v1/fixtures/can-settle-payout.ts"), "utf8"),
    ]);
    expect(obligations).not.toBe(mutants);
    expect(obligations).not.toMatch(/generator|adapter|compiler/u);
    expect(mutants).not.toMatch(/generator|adapter|compiler/u);
    expect(source).toContain("Handwritten candidate fixture");
    expect(source).not.toMatch(/generated by|TODO business body/u);
  });
});
