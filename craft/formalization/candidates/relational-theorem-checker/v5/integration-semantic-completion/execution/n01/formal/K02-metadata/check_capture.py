"""Compare the explicit Lean byte literal with the pinned source fixture; no parser proof."""
from pathlib import Path
import hashlib
import json
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[9]


def run():
    capture = json.loads((HERE / 'source-capture.json').read_text())
    for key in ['fixture', 'schema', 'generated_fixture', 'parsed_AST_fixture']:
        item = capture[key]
        path = ROOT / item['path']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == item['sha256']
    fixture = (ROOT / capture['fixture']['path']).read_bytes()
    source = (HERE / 'MetadataFixture.lean').read_text()
    matched = re.search(r'def originalBytes : List UInt8 := \[([^]]*)\]', source)
    assert matched
    literal = bytes(int(value.strip()) for value in matched.group(1).split(','))
    assert literal == fixture and len(fixture) == capture['original_byte_count']
    result = {'result': 'original-byte-literal-comparison-pass', 'byte_count': len(fixture),
              'parser_proof': False, 'authenticity_proof': False,
              'claim_scope': 'Exact equality of a source file and a generated byte literal only.'}
    def binding(path):
        return {'path': str(path.relative_to(ROOT)),
                'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
    result.update(driver=binding(Path(__file__)), source_capture=binding(HERE / 'source-capture.json'),
                  fixture=capture['fixture'], generated_fixture=capture['generated_fixture'],
                  inherited_discharges=0, authority_effect='none')
    (HERE / 'capture-comparison-audit.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps({'result': result['result'], 'byte_count': result['byte_count']}))


if __name__ == '__main__':
    run()
