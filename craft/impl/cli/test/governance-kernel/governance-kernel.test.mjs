import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

import {
  GovernanceKernelContractError,
  checkGovernanceKernel,
  materializeGovernanceKernel,
  renderGovernanceKernel
} from "../../tools/governance-kernel.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = path.resolve(HERE, "../../../../../..");
const WRITABLE_TEMP_ROOT = process.platform === "linux" ? "/tmp" : os.tmpdir();
const PROJECT_ROOT = path.join(
  REPOSITORY_ROOT,
  "cyberAlchemy-v2/development/examples/smallest-governance-program/domainspec"
);

test("closed DomainSpec source renders deterministic no-effect Rust artifacts", () => {
  const first = renderGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: PROJECT_ROOT });
  const second = renderGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: PROJECT_ROOT });
  assert.deepEqual([...first.outputs], [...second.outputs]);
  assert.equal(first.model.accepted.baselineId, "domainspec-meta-types-current-implemented@3");
  const receipt = JSON.parse(first.outputs.get("DOMAINSPEC-INSTANTIATION-RECEIPT.json").toString("utf8"));
  assert.equal(receipt.evaluation_hashing, "none");
  assert.equal(receipt.type_hash_protocol, "rust-hash-trait-for-equality-not-invoked-by-evaluator");
  assert.equal(receipt.lifecycle_clock, "explicit-program-version-only");
  assert.equal(receipt.authority_effect, "none");
  assert.equal(receipt.enforcement_effect, "none");
  assert.equal(receipt.meta_type_bindings.length, 6);
});

test("materialize followed by check proves exact generated bytes", () => {
  const temporary = fs.mkdtempSync(path.join(WRITABLE_TEMP_ROOT, "domainspec-governance-kernel-"));
  materializeGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: PROJECT_ROOT, outputRoot: temporary });
  checkGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: PROJECT_ROOT, outputRoot: temporary });
  fs.appendFileSync(path.join(temporary, "src/lib.rs"), "// drift\n");
  assert.throws(
    () => checkGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: PROJECT_ROOT, outputRoot: temporary }),
    (error) => error instanceof GovernanceKernelContractError && error.code === "GKC_TARGET_DRIFT"
  );
});

test("meta-type drift fails before generation", () => {
  const temporary = fs.mkdtempSync(path.join(WRITABLE_TEMP_ROOT, "domainspec-governance-source-"));
  fs.cpSync(PROJECT_ROOT, temporary, { recursive: true });
  const nodePath = path.join(temporary, "specs/governance-evaluation-kernel/nodes/governance-program.json");
  const node = JSON.parse(fs.readFileSync(nodePath, "utf8"));
  node.body.meta_type_id = "DS-D1.2";
  fs.writeFileSync(nodePath, `${JSON.stringify(node, null, 2)}\n`);
  assert.throws(
    () => renderGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: temporary }),
    (error) => error instanceof GovernanceKernelContractError && error.code === "GKC_CONTRACT"
  );
});

test("evaluator contains no hash invocation or effect executor", () => {
  const rendered = renderGovernanceKernel({ repositoryRoot: REPOSITORY_ROOT, projectRoot: PROJECT_ROOT });
  const rust = rendered.outputs.get("src/lib.rs").toString("utf8");
  const runtime = rust.split("#[cfg(test)]", 1)[0];
  const evaluator = runtime.slice(runtime.indexOf("fn calculate_governance"), runtime.indexOf("fn clause_accepts_fact"));
  assert.doesNotMatch(runtime, /Sha256|DefaultHasher|std::fs|std::process::Command/);
  assert.doesNotMatch(evaluator, /\.hash\(/);
  assert.match(rust, /pub const ENFORCEMENT_EFFECT: &str = "none"/);
  assert.match(rust, /pub const EVALUATE_GOVERNANCE: GovernanceCalculation/);
});
